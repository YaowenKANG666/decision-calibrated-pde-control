"""Recompute release metrics from saved JSON and CSV source files.

The audit checks numerical consistency, sample counts, matched-control design,
coverage denominators, and metric semantics. It does not certify that a saved
experiment was generated by a particular executable or hardware environment.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from pathlib import Path

import numpy as np


def load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def load_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as stream:
        return list(csv.DictReader(stream))


def wilson_interval(successes: int, total: int, z: float = 1.96) -> tuple[float, float]:
    proportion = successes / total
    denominator = 1.0 + z**2 / total
    center = (proportion + z**2 / (2.0 * total)) / denominator
    radius = (
        z
        * math.sqrt(
            proportion * (1.0 - proportion) / total + z**2 / (4.0 * total**2)
        )
        / denominator
    )
    return center - radius, center + radius


def log_slope(x: np.ndarray, y: np.ndarray) -> float:
    return float(np.polyfit(np.log(x), np.log(y), 1)[0])


class Audit:
    def __init__(self) -> None:
        self.checks: list[dict[str, object]] = []
        self.coverage: list[dict[str, object]] = []

    def check(self, name: str, condition: bool, detail: str) -> None:
        self.checks.append(
            {"name": name, "status": "PASS" if condition else "FAIL", "detail": detail}
        )

    def close(self, name: str, observed: float, expected: float, tolerance: float = 1e-10) -> None:
        difference = abs(observed - expected)
        self.check(
            name,
            difference <= tolerance,
            f"observed={observed:.12g}, stored={expected:.12g}, abs_diff={difference:.3g}",
        )

    def coverage_check(self, name: str, proportion: float, total: int, target: float) -> None:
        successes = round(proportion * total)
        exact_count = abs(successes / total - proportion) <= 1e-12
        lower, upper = wilson_interval(successes, total)
        self.coverage.append(
            {
                "name": name,
                "successes": successes,
                "total": total,
                "observed": proportion,
                "target": target,
                "wilson_95": [lower, upper],
                "target_in_wilson_95": lower <= target <= upper,
            }
        )
        self.check(
            f"{name}: integer denominator",
            exact_count,
            f"{successes}/{total}={successes / total:.12g}",
        )

    @property
    def passed(self) -> bool:
        return all(row["status"] == "PASS" for row in self.checks)


def audit_burgers(root: Path, audit: Audit) -> dict:
    payload = load_json(root / "results/fno_burgers_seed27/fno_metrics.json")
    protocol = payload["data_protocol"]
    audit.check("Burgers backbone is FNO", payload["model"] == "fno", str(payload["model"]))
    audit.check(
        "FNO architecture recorded",
        payload["architecture"] == {"width": 32, "modes": 14, "layers": 4},
        json.dumps(payload["architecture"], sort_keys=True),
    )
    audit.check(
        "FNO pair parameter count is positive",
        int(payload["parameters"]) == 240454,
        f"parameters={payload['parameters']}",
    )

    expected_cases = int(protocol["control_cases"])
    expected_horizon = int(protocol["control_horizon"])
    for method, values in payload["control"].items():
        raw = np.asarray(values["raw"], dtype=float)
        actions = np.asarray(values["actions"], dtype=float)
        audit.check(
            f"{method}: control shape",
            raw.shape == (expected_cases,) and actions.shape == (expected_cases, expected_horizon),
            f"costs={raw.shape}, actions={actions.shape}",
        )
        audit.check(
            f"{method}: finite values",
            bool(np.isfinite(raw).all() and np.isfinite(actions).all()),
            "costs and actions are finite",
        )
        audit.close(f"{method}: mean", float(raw.mean()), float(values["mean"]))
        audit.close(f"{method}: standard deviation", float(raw.std()), float(values["std"]))
        audit.close(f"{method}: p90", float(np.quantile(raw, 0.90)), float(values["p90"]))
        audit.close(
            f"{method}: mean absolute action",
            float(np.abs(actions).mean()),
            float(values["mean_absolute_action"]),
        )

    cases = payload["control_cases"]
    for field in ("viscosity", "left_boundary", "right_boundary"):
        unique = {round(float(case[field]), 14) for case in cases}
        audit.check(
            f"Matched control cases share {field}",
            len(unique) == 1,
            f"unique_values={len(unique)}",
        )
    gains = np.asarray([case["actuator_gain"] for case in cases], dtype=float)
    audit.check(
        "Actuator-gain sweep is strictly ordered",
        len(gains) == expected_cases and bool(np.all(np.diff(gains) > 0.0)),
        f"n={len(gains)}, range=[{gains.min():.3g}, {gains.max():.3g}]",
    )

    combined = payload["evaluation"]["combined_shift"]
    test_size = int(protocol["test_per_regime"])
    for key in ("id_l2", "audit_l2", "audit_ellipsoid", "audit_simultaneous_box"):
        audit.coverage_check(
            f"Burgers combined shift {key}",
            float(combined[key]["coverage"]),
            test_size,
            0.90,
        )
    audit.coverage_check(
        "Burgers behavior trajectory",
        float(payload["trajectory_evaluation"]["coverage"]),
        int(protocol["trajectory_test"]),
        0.90,
    )
    return payload


def audit_bounds(root: Path, audit: Audit) -> dict:
    result_root = root / "experiments/bound_comparison_reference"
    summary = load_json(result_root / "results/summary.json")
    rows = load_csv(result_root / "data/test_case_bounds.csv")
    gaps = np.asarray([float(row["observed_value_gap"]) for row in rows])
    audit.check(
        "Value-bound test row count",
        len(rows) == int(summary["test_cases"]),
        f"rows={len(rows)}, stored={summary['test_cases']}",
    )
    for stored in summary["table"]:
        key = stored["method_key"]
        bounds = np.asarray([float(row[f"{key}_bound"]) for row in rows])
        utilization = gaps / np.maximum(bounds, 1e-12)
        computed = {
            "coverage": float(np.mean(gaps <= bounds)),
            "mean_bound": float(np.mean(bounds)),
            "median_utilization": float(np.median(utilization)),
            "p90_utilization": float(np.quantile(utilization, 0.90)),
            "max_utilization": float(np.max(utilization)),
            "mean_value_gap": float(np.mean(gaps)),
        }
        for metric, value in computed.items():
            audit.close(f"Value bound {key}: {metric}", value, float(stored[metric]))
        audit.coverage_check(
            f"Value bound {key}",
            computed["coverage"],
            len(rows),
            float(summary["target_coverage"]),
        )
    return summary


def audit_value_scaling(root: Path, audit: Audit) -> dict:
    result_root = root / "experiments/value_gap_reference"
    summary = load_json(result_root / "results/summary.json")
    rows = load_csv(result_root / "data/analytic_sharpness.csv")
    epsilon_rows = [
        row
        for row in rows
        if float(row["gamma"]) == 0.95 and float(row["dynamics_lipschitz"]) == 1.0
    ]
    gamma_rows = [
        row
        for row in rows
        if float(row["epsilon"]) == 0.01 and float(row["dynamics_lipschitz"]) == 1.0
    ]
    epsilon_slope = log_slope(
        np.asarray([float(row["epsilon"]) for row in epsilon_rows]),
        np.asarray([float(row["exact_fixed_policy_bound"]) for row in epsilon_rows]),
    )
    gamma = np.asarray([float(row["gamma"]) for row in gamma_rows])
    gamma_slope = log_slope(
        1.0 / (1.0 - gamma),
        np.asarray([float(row["normalized_gamma_gap"]) for row in gamma_rows]),
    )
    audit.close(
        "Value-gap epsilon slope",
        epsilon_slope,
        float(summary["analytic"]["epsilon_log_log_slope"]),
    )
    audit.close(
        "Value-gap effective-horizon slope",
        gamma_slope,
        float(summary["analytic"]["discount_horizon_log_log_slope"]),
    )
    simulation_error = max(
        abs(float(row["simulation_to_exact_ratio"]) - 1.0) for row in rows
    )
    audit.close(
        "Value-gap maximum numerical error",
        simulation_error,
        float(summary["analytic"]["max_simulation_relative_error"]),
        tolerance=1e-14,
    )
    return summary


def audit_ns2d(root: Path, audit: Audit) -> dict:
    result_root = root / "experiments/ns2d_reference"
    metrics = load_json(result_root / "results/metrics.json")
    curves = load_csv(result_root / "data/coverage_width.csv")
    history = load_csv(result_root / "data/training_history.csv")
    audit.check(
        "NS2D metric is named RMSE",
        "mean_rmse" in metrics and "mean_l2_error" not in metrics,
        metrics.get("rmse_definition", "missing definition"),
    )
    audit.check(
        "NS2D split sizes are positive",
        all(int(metrics[key]) > 0 for key in ("n_train", "n_validation", "n_audit", "n_test")),
        (
            f"train/validation/audit/test={metrics['n_train']}/{metrics['n_validation']}/"
            f"{metrics['n_audit']}/{metrics['n_test']}"
        ),
    )
    audit.check(
        "NS2D training history length",
        len(history) == 20,
        f"epochs={len(history)}",
    )
    history_values = np.asarray(
        [[float(row["train_mse"]), float(row["validation_mse"])] for row in history]
    )
    audit.check(
        "NS2D training history is finite and nonnegative",
        bool(np.isfinite(history_values).all() and (history_values >= 0.0).all()),
        "all stored train/validation MSE values checked",
    )
    target_row = next(row for row in curves if float(row["nominal_coverage"]) == 0.90)
    audit.close(
        "NS2D 90% curve coverage",
        float(target_row["test_coverage"]),
        float(metrics["test_simultaneous_coverage"]),
    )
    audit.close(
        "NS2D 90% quantile",
        float(target_row["quantile"]),
        float(metrics["q90"]),
    )
    audit.close(
        "NS2D 90% full width",
        float(target_row["mean_full_width"]),
        float(metrics["mean_full_band_width"]),
        tolerance=1e-6,
    )
    audit.coverage_check(
        "NS2D simultaneous field",
        float(metrics["test_simultaneous_coverage"]),
        int(metrics["n_test"]),
        0.90,
    )
    return metrics


def render_markdown(report: dict) -> str:
    lines = [
        "# Release data audit",
        "",
        f"Overall status: **{report['status']}**.",
        "",
        "This audit recomputes reported summaries from the saved JSON and CSV source files.",
        "It checks internal numerical consistency; it is not a cryptographic provenance proof.",
        "",
        "## Numerical checks",
        "",
        "| Check | Status | Detail |",
        "|---|---|---|",
    ]
    for row in report["checks"]:
        detail = str(row["detail"]).replace("|", "\\|")
        lines.append(f"| {row['name']} | {row['status']} | {detail} |")
    lines.extend(
        [
            "",
            "## Coverage denominators and sampling uncertainty",
            "",
            "The intervals below are descriptive 95% Wilson intervals for the realized test",
            "proportions. They are not replacements for the split-conformal theorem.",
            "",
            "| Event | Count | Observed | Target | Wilson 95% | Target inside |",
            "|---|---:|---:|---:|---:|---|",
        ]
    )
    for row in report["coverage"]:
        lower, upper = row["wilson_95"]
        lines.append(
            f"| {row['name']} | {row['successes']}/{row['total']} | "
            f"{row['observed']:.4f} | {row['target']:.2f} | "
            f"[{lower:.4f}, {upper:.4f}] | "
            f"{'yes' if row['target_in_wilson_95'] else 'no'} |"
        )
    lines.extend(
        [
            "",
            "## Metric correction",
            "",
            "The NS2D value 0.163472 is a mean field RMSE, not a relative L2 error.",
            "The implementation, manuscript, README, and stored metric key now use the RMSE label.",
            "No numerical value was changed by this semantic correction.",
            "",
            "## Scope",
            "",
            "The Burgers controller table contains 24 matched actuator-gain cases from one",
            "trained FNO pair. The NS2D result also conditions on one trained FNO pair. These",
            "checks support internal consistency and mechanism-level interpretation, not",
            "population-level uncertainty across training seeds.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--project-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("results/data_integrity"),
    )
    args = parser.parse_args()
    root = args.project_root.resolve()
    output = args.output_dir if args.output_dir.is_absolute() else root / args.output_dir

    audit = Audit()
    audit_burgers(root, audit)
    audit_bounds(root, audit)
    audit_value_scaling(root, audit)
    audit_ns2d(root, audit)
    report = {
        "status": "PASS" if audit.passed else "FAIL",
        "checks": audit.checks,
        "coverage": audit.coverage,
    }
    output.mkdir(parents=True, exist_ok=True)
    (output / "data_audit.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    (output / "DATA_AUDIT.md").write_text(render_markdown(report), encoding="utf-8")
    print(output / "DATA_AUDIT.md")
    if not audit.passed:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
